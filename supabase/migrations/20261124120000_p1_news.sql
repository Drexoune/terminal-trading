-- Plan « Tout en ligne », étape O6 (fil d'actus E6) : table des titres et diffusion au front.
--
-- 1. news_items : chaque titre gardé par la tâche « news » de p1-jobs (après les quatre couches
--    de doublons), dans sa langue d'origine (T-019), avec la règle qui l'a classé et l'empreinte
--    de la version des règles. RLS active, aucune politique : la clé publishable ne lit rien.
-- 2. p1_state_broadcast : la liste des clés diffusées sur le canal public « p1-public » gagne
--    les titres (news:item:…), l'état des flux (news:feeds) et le flux du terminal (feed:news).
--    Toujours jamais diffusés : verrous (lock:…), alertes (alert:…, données personnelles),
--    état interne de l'API du BLS (release:api-…).

create table public.news_items (
  id            bigint generated by default as identity primary key,
  feed          text not null,                 -- fed-monetary, ecb-press… financialjuice
  source        text not null,                 -- libellé affiché : Fed, BCE, FinancialJuice
  kind          text not null,                 -- officielle, agence
  native_id     text,                          -- guid du flux
  url           text,                          -- URL canonique (couche 2 des doublons)
  title         text not null,
  title_norm    text not null,                 -- couche 3 des doublons
  numbers       text not null default '',      -- nombres du titre : jamais fusionnés s'ils diffèrent
  summary       text,
  category      text not null,                 -- banque-centrale, macro, crypto, matieres-premieres, general
  urgent        boolean not null default false,
  rule          text,                          -- decision:FED, figure:major…
  rules_version text not null,
  figure        jsonb,                         -- chiffre structuré de FinancialJuice
  published_ms  bigint,                        -- heure de la source (UTC), null si illisible
  published_raw text,
  received_ms   bigint not null,               -- heure de lecture par la tâche
  backfill      boolean not null default false,-- arriéré : affiché, jamais annoncé
  unique (url)
);
create index news_items_received on public.news_items (received_ms);
alter table public.news_items enable row level security;
revoke all on public.news_items from anon, authenticated;

create or replace function public.p1_state_broadcast()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.key like 'calendar:%'
     or new.key in ('feed:calendar', 'feed:bls-calendar', 'feed:news', 'news:feeds', 'release:state', 'release:last')
     or new.key like 'release:us-%'
     or new.key like 'reaction:%'
     or new.key like 'news:item:%' then
    perform realtime.send(
      jsonb_build_object('key', new.key, 'value', new.value, 'updated_ms', new.updated_ms),
      'state',
      'p1-public',
      false
    );
  end if;
  return null;
end;
$$;
revoke all on function public.p1_state_broadcast() from public, anon, authenticated;
