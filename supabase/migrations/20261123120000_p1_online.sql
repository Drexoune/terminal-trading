-- Plan « Tout en ligne », étape O1 (docs/plan-online.md, décisions T-042 à T-046) :
-- tables de P1 (agenda, capture du BLS, alertes) dans Supabase.
--
-- Mêmes tables, mêmes colonnes, mêmes contraintes que la base SQLite de la passerelle
-- (gateway/terminal_gateway/storage.py, migrations 1 à 6) : un test
-- (gateway/tests/test_online_schema.py) fait échouer la CI si les deux divergent.
-- Mêmes conventions : heures en millisecondes UTC (bigint), valeurs publiées en texte
-- décimal, jamais de flottant pour un chiffre officiel.
--
-- Accès : RLS activée SANS aucune politique (T-012, maintenue par T-043). Seule la clé
-- secrète (Edge Functions, fonctions Vercel) lit et écrit. La clé publishable du front
-- (T-043) ne servira qu'au canal Realtime public, jamais à lire ces tables.
--
-- Identifiants : « generated by default as identity », pour que la copie des données du
-- Mac (scripts/p1_copy_to_supabase.py) garde ses identifiants ; p1_sync_sequences()
-- recale ensuite les compteurs.

-- 1. agenda ----------------------------------------------------------------------------

create table public.indicators (
  id              text primary key,            -- « us-cpi-mm »
  label_fr        text not null,
  currency        text not null,
  official_series text,                        -- « CUSR0000SA0 »
  unit            text,
  decimals        integer,
  ff_series       text unique,                 -- série ForexFactory (« 78-us-cpi-mm »)
  capture         integer not null default 0   -- 1 : capté à la source
);

create table public.calendar_snapshots (
  id           bigint generated by default as identity primary key,
  source       text not null,                  -- « ForexFactory »
  url          text not null,
  status       integer not null,
  source_ts_ms bigint,                         -- Last-Modified
  received_ms  bigint not null,
  etag         text,
  sha256       text,
  body         bytea                           -- contenu brut (null sur 304) : archive privée (T-018)
);
create index calendar_snapshots_received on public.calendar_snapshots (received_ms);

create table public.calendar_events (
  id               bigint generated by default as identity primary key,
  identity         text not null,              -- série|devise|jour New York|rang
  indicator_id     text references public.indicators (id),
  title            text not null,
  currency         text not null,
  ff_time_ms       bigint,
  ff_time_kind     text,
  official_time_ms bigint,
  official_local   text,
  official_tz      text,
  impact           text,
  forecast_raw     text,
  forecast         text,
  previous_raw     text,
  status           text not null default 'prévu',
  first_seen_ms    bigint not null,
  last_seen_ms     bigint not null,
  snapshot_id      bigint references public.calendar_snapshots (id),
  -- « nulls not distinct » : plus strict que SQLite, qui tient deux NULL pour distincts ; aucune
  -- ligne du Mac n'a de NULL dans cette clé (vérifié le 23/11/2026).
  unique nulls not distinct (identity, forecast_raw, previous_raw, ff_time_ms, status)
);
create index calendar_events_identity on public.calendar_events (identity, last_seen_ms);
create index calendar_events_time on public.calendar_events (ff_time_ms);

create table public.official_releases (
  id            bigint generated by default as identity primary key,
  source        text not null,                 -- « BLS »
  title         text not null,
  local_date    text not null,
  local_time    text not null,
  tz            text not null,                 -- zone IANA
  utc_ms        bigint not null,
  first_seen_ms bigint not null,
  last_seen_ms  bigint not null,
  unique (source, title, local_date, local_time)
);
create index official_releases_time on public.official_releases (utc_ms);

-- 2. capture à l'heure H, suites -----------------------------------------------------------

create table public.releases (
  id               bigint generated by default as identity primary key,
  indicator_id     text not null references public.indicators (id),
  release          text not null,              -- « cpi », « empsit », « ppi », « prod2 »
  period           text not null,
  edition          text not null default '',
  ny_date          text not null,
  value            text,                       -- texte décimal tel que publié ; null si non lu
  reason           text,
  part             text,
  excerpt          text,
  flags            text not null default '[]', -- JSON
  timing           text not null,
  nature           text not null default 'officielle',
  scheduled_ms     bigint not null,
  embargo_ms       bigint,
  first_byte_ms    bigint,
  received_ms      bigint not null,
  url              text not null,
  machine          text not null,              -- « supabase » pour la capture en ligne
  forecast         text,
  forecast_raw     text,
  forecast_seen_ms bigint,
  surprise         text,
  z                text,
  z_n              integer,
  z_reason         text,
  regular          integer not null default 1,
  filled_ms        bigint,                     -- complété par l'API v1 (T-041)
  unique (indicator_id, period, edition)
);
create index releases_indicator on public.releases (indicator_id, scheduled_ms);

create table public.release_timings (
  id              bigint generated by default as identity primary key,
  release         text not null,
  period          text not null,
  edition         text not null default '',
  scheduled_ms    bigint not null,
  last_without_ms bigint,
  first_send_ms   bigint,
  first_byte_ms   bigint,
  parsed_ms       bigint,
  bus_ms          bigint,
  display_ms      bigint,
  okx_offset_ms   double precision,
  date_header     text,
  unique (release, period, edition)
);

create table public.release_polls (
  id            bigint generated by default as identity primary key,
  release       text not null,
  scheduled_ms  bigint not null,
  label         text not null,
  url           text not null,
  send_ms       bigint not null,
  first_byte_ms bigint,
  done_ms       bigint,
  status        integer,
  size          integer,
  null_bytes    integer,
  period        text,
  embargo_date  text,
  verdict       text,
  error         text
);
create index release_polls_sched on public.release_polls (release, scheduled_ms);

create table public.release_revisions (
  id           bigint generated by default as identity primary key,
  indicator_id text not null references public.indicators (id),
  period       text not null,
  edition      text not null default '',
  kind         text not null,                  -- « révision » ou « écart »
  previous     text not null,
  value        text not null,
  source       text not null,
  series       text,
  excerpt      text,
  seen_ms      bigint not null,
  poll_id      bigint references public.release_polls (id)
);
create index release_revisions_ind on public.release_revisions (indicator_id, period, seen_ms);

create table public.release_reactions (
  id           bigint generated by default as identity primary key,
  release      text not null,
  ny_date      text not null,
  scheduled_ms bigint not null,
  inst         text not null,
  source       text not null,
  candles      text not null,                  -- JSON
  ref_price    text,
  end_price    text,
  change_pct   text,
  missing      text not null default '[]',
  reason       text,
  received_ms  bigint not null,
  unique (release, ny_date)
);

-- 3. alertes -------------------------------------------------------------------------------

create table public.alert_rules (
  id            bigint generated by default as identity primary key,
  kind          text not null,
  params        text not null,                 -- JSON
  channels      text not null,                 -- JSON
  state         text not null default 'armée',
  created_ms    bigint not null,
  updated_ms    bigint not null,
  last_fired_ms bigint
);

create table public.alert_events (
  id             text primary key,
  rule_id        bigint not null references public.alert_rules (id) on delete cascade,
  dedupe         text not null,
  fired_ms       bigint not null,
  title          text not null,
  body           text,
  source         text,
  source_ms      bigint,
  data           text not null default '{}',   -- JSON
  telegram       text,
  telegram_ms    bigint,
  telegram_error text,
  acked_ms       bigint,
  unique (rule_id, dedupe)
);
create index alert_events_fired on public.alert_events (fired_ms);

