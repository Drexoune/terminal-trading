-- 5. compteurs après la copie des données du Mac -----------------------------------------------
-- Appelée une fois par scripts/p1_copy_to_supabase.py, avec la clé secrète seulement.

create or replace function public.p1_sync_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  t text;
begin
  foreach t in array array['calendar_snapshots', 'calendar_events', 'official_releases', 'releases',
                           'release_timings', 'release_polls', 'release_revisions', 'release_reactions',
                           'alert_rules'] loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from public.%I), 0) + 1, false)',
      'public.' || t, t);
  end loop;
end;
$$;
revoke all on function public.p1_sync_sequences() from public, anon, authenticated;
grant execute on function public.p1_sync_sequences() to service_role;
