-- Journal de trading (P6, S5, T-074) : saisie manuelle depuis l'écran Track record, par la fonction
-- Bourse (/api/bourse/journal) derrière le mot de passe d'application (T-031). RLS active, aucune
-- politique : seule la clé secrète (fonctions Vercel) lit et écrit ; la clé publishable ne lit rien.

create table public.journal_trades (
  id          bigint generated by default as identity primary key,
  opened_ms   bigint not null,
  closed_ms   bigint,
  asset       text not null,
  side        text not null check (side in ('long', 'short')),
  qty         double precision not null check (qty > 0),
  entry       double precision not null check (entry > 0),
  exit        double precision check (exit > 0),
  stop        double precision check (stop > 0),
  fees        double precision not null default 0 check (fees >= 0),
  setup       text,
  notes       text,
  created_ms  bigint not null,
  updated_ms  bigint not null,
  check ((exit is null) = (closed_ms is null))
);
create index journal_trades_opened on public.journal_trades (opened_ms desc);
alter table public.journal_trades enable row level security;
revoke all on public.journal_trades from anon, authenticated;
